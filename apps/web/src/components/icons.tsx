// Tiny inline SVG icons. Project convention bans decorative emoji in
// shipped UI; these are visually equivalent and accessibility-clean.
//
// Each icon takes the same minimal props (className, label) and renders at
// 1em so it inherits the surrounding text size.

interface IconProps {
  className?: string;
  label?: string;
}

function iconShell(label: string | undefined) {
  return label
    ? { role: "img" as const, "aria-label": label }
    : { "aria-hidden": true };
}

export function LockIcon({ className, label }: IconProps) {
  return (
    <svg
      viewBox="0 0 24 24"
      width="1em"
      height="1em"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      {...iconShell(label)}
    >
      <rect x="4" y="11" width="16" height="9" rx="2" />
      <path d="M8 11V8a4 4 0 0 1 8 0v3" />
    </svg>
  );
}

